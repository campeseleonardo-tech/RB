#!/usr/bin/env python3
"""Write research/data_summary.md: the usable data of data/ ordered by research question (RQ1-RQ5).

Run:  python research/build_data_summary.py
Scope as in project/project_memory.md: 15 cities, their 9 countries, breaking (reference) and
salsa/bachata (case). Only rows that are not `not_found` are shown as values; the coverage table
counts how many cells of each indicator hold a value. Standard library only.
"""

import csv
import datetime
import os
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data")
OUT = os.path.join(ROOT, "research", "data_summary.md")

CITIES = ["SBG", "INN", "GRZ", "VIE", "MUC", "BER", "ZRH", "MIL", "ROM", "BCN", "MAD", "PAR", "AMS", "LON", "WAW"]
COUNTRIES = ["AT", "DE", "CH", "IT", "ES", "FR", "NL", "UK", "PL"]
DISCS = ["URB-BRK", "CAR-SAL", "CAR-BCH"]
DLABEL = {"URB-BRK": "Breaking", "CAR-SAL": "Salsa", "CAR-BCH": "Bachata"}

# Indicators of the research questions: (RQ, label, level, signal, unit). One row per cell.
INDICATORS = [
    ("RQ1", "Schools with a weekly class", "city", "SCH", "schools with a weekly class (fixed search)"),
    ("RQ1", "Weekly class slots", "city", "SCH", "weekly class slots (schools of R1.1)"),
    ("RQ1", "Recurring socials / jams", "city", "COM", "recurring socials or jams (named, active 2026)"),
    ("RQ2", "Competitors in the national championship", "country", "CMP", "competitors in the national championship (results list)"),
    ("RQ2", "Competitions held in the city (12 months)", "city", "CMP", "competitions held in the city (12 months)"),
    ("RQ2", "Ladder rungs present (1-5)", "country", "LAD", "rungs present"),
    ("RQ3", "Events listed on the reference platform (12 months)", "city", "EVT", None),
    ("RQ3", "Largest event identified", "city", "EVT", "largest event identified in the city (2025 or 2026)"),
    ("RQ3", "Full pass price, largest event", "city", "PRC", "EUR full pass, largest event"),
    ("RQ3", "Countries of participants, largest event", "city", "EVT", "countries of participants stated, largest event"),
    ("RQ4", "Spectators stated", "city", "MED", "spectators stated"),
    ("RQ5", "Red Bull dance events 2024-2026", "city", "ORG", "Red Bull dance events 2024-2026"),
]


def load(name):
    with open(os.path.join(DATA, name), encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def val(f):
    if f["value"]:
        return f["value"]
    if f["value_low"] or f["value_high"]:
        return f"{f['value_low']}-{f['value_high']}"
    return ""


def fmt_num(v):
    try:
        n = float(v)
    except ValueError:
        return v
    return f"{int(n):,}" if n == int(n) else f"{n:,}"


def main():
    facts = load("facts.csv")
    events = {e["event_id"]: e for e in load("events.csv")}
    orgs = load("organisations.csv")
    rels = load("relations.csv")
    places = {p["place_id"]: p for p in load("places.csv")}
    org_by_id = {o["org_id"]: o for o in orgs}

    real = [f for f in facts if f["evidence_type"] != "not_found"]
    by_cell = defaultdict(list)
    tried = defaultdict(list)
    for f in facts:
        key = (f["place_id"], f["disc_id"], f["signal_id"], f["unit"])
        (tried if f["evidence_type"] == "not_found" else by_cell)[key].append(f)

    def cell(place, disc, signal, unit):
        if unit is None:
            rows = [f for f in real if f["place_id"] == place and f["disc_id"] == disc and f["signal_id"] == signal
                    and f["unit"].startswith("events listed on")]
        else:
            rows = by_cell.get((place, disc, signal, unit), [])
        rows = sorted(rows, key=lambda f: {"H": 0, "M": 1, "L": 2}.get(f["confidence"], 3))
        return rows[0] if rows else None

    def searched(place, disc, signal, unit):
        if unit is None:
            return any(f["place_id"] == place and f["disc_id"] == disc and f["unit"].startswith("events listed on")
                       for f in facts if f["evidence_type"] == "not_found")
        return bool(tried.get((place, disc, signal, unit)))

    out = []
    w = out.append
    w("# Data summary by research question")
    w("")
    w(f"Generated by research/build_data_summary.py on {datetime.date.today().isoformat()} from data/. Do not edit by hand: re-run the script.")
    w("Scope: 15 cities, 9 countries, breaking (reference) and salsa/bachata (case); research questions in project/project_memory.md section 3.")
    w("Legend: a value = a non-not_found record (found, stated_by_organiser, or inferred); check the fact notes and confidence for minimums or other limits. `nf` = searched, not found or not measurable (reason in the row notes); `—` = not searched yet.")
    w("")

    # Coverage
    w("## 1. Coverage per indicator")
    w("")
    w("| RQ | Indicator | Level | Breaking | Salsa | Bachata |")
    w("|---|---|---|---|---|---|")
    for rq, label, level, signal, unit in INDICATORS:
        places_ = CITIES if level == "city" else COUNTRIES
        cols = []
        for d in DISCS:
            have = sum(1 for p in places_ if cell(p, d, signal, unit))
            nf = sum(1 for p in places_ if not cell(p, d, signal, unit) and searched(p, d, signal, unit))
            cols.append(f"{have}/{len(places_)}" + (f" (nf {nf})" if nf else ""))
        w(f"| {rq} | {label} | {level} | " + " | ".join(cols) + " |")
    w("")

    # RQ2 by country
    w("## 2. RQ2 Competitions, by country")
    w("")
    w("Competitors in the last national championship (from results lists) and ladder rungs present (1 class, 2 social/jam, 3 local battle, 4 national, 5 international).")
    w("")
    w("| Country | Breaking: competitors | Salsa/bachata: competitors | Breaking: rungs | Salsa: rungs |")
    w("|---|---|---|---|---|")
    for c in COUNTRIES:
        def show(d, s, u):
            f = cell(c, d, s, u)
            if f:
                return fmt_num(val(f))
            return "nf" if searched(c, d, s, u) else "—"
        comp_unit = "competitors in the national championship (results list)"
        lat = show("CAR-SAL", "CMP", comp_unit)
        bch = show("CAR-BCH", "CMP", comp_unit)
        latin = lat if lat == bch else f"{lat} / {bch}"
        w(f"| {places[c]['name']} | {show('URB-BRK', 'CMP', comp_unit)} | {latin} | "
          f"{show('URB-BRK', 'LAD', 'rungs present')} | {show('CAR-SAL', 'LAD', 'rungs present')} |")
    w("")
    w("Organisations that run competitions (organisations.csv, federations and organisers with a `governs` or `organises` link):")
    w("")
    linked = {r["from_id"] for r in rels if r["from_type"] == "org" and r["relation"] in ("governs", "organises")}
    groups = defaultdict(list)
    for o in orgs:
        if o["org_id"] in linked and (o["place_id"] in COUNTRIES or o["place_id"] == "GLOBAL"):
            groups[o["place_id"]].append(f"{o['name']} ({DLABEL.get(o['disc_id'], o['disc_id'])})")
    for key in COUNTRIES + ["GLOBAL"]:
        if groups.get(key):
            name = "International" if key == "GLOBAL" else places[key]["name"]
            w(f"- **{name}**: " + "; ".join(sorted(groups[key])))
    w("")
    quals = [r for r in rels if r["relation"] == "qualifies_for"]
    if quals:
        w("Qualification links (relations.csv `qualifies_for`):")
        w("")
        for r in quals:
            w(f"- {r['from_id']} -> {r['to_id']}" + (f" ({r['notes'][:90]})" if r["notes"] else ""))
        w("")

    # City table
    w("## 3. RQ1, RQ3, RQ5 by city")
    w("")
    w("| City | Population (city) | Red Bull dance events 2024-26 | Largest breaking event | Largest Latin event | Socials/jams (salsa, bachata, breaking) |")
    w("|---|---|---|---|---|---|")
    for c in CITIES:
        pops = [f for f in real if f["place_id"] == c and f["disc_id"] == "ALL" and f["signal_id"] == "POP"]
        city_pop = [f for f in pops if "city proper" in (f["notes"] + f["unit"]).lower() or "urb_cpop1" in f["notes"]]
        pop = (city_pop or pops)
        pop_txt = fmt_num(val(pop[0])) if pop else "—"
        rb = cell(c, "URB-BRK", "ORG", "Red Bull dance events 2024-2026")
        rb_txt = val(rb) if rb else "—"

        def largest(discs):
            for d in discs:
                f = cell(c, d, "EVT", "largest event identified in the city (2025 or 2026)")
                if f and val(f) in events:
                    e = events[val(f)]
                    size = f"{fmt_num(e['scale_value'])} {e['scale_type']}" if e["scale_value"] else "size nf"
                    return f"{e['name']} ({size})"
            return "nf" if any(searched(c, d, "EVT", "largest event identified in the city (2025 or 2026)") for d in discs) else "—"
        soc = []
        for d in ["CAR-SAL", "CAR-BCH", "URB-BRK"]:
            f = cell(c, d, "COM", "recurring socials or jams (named, active 2026)")
            soc.append(val(f) if f else "—")
        w(f"| {places[c]['name']} | {pop_txt} | {rb_txt} | {largest(['URB-BRK'])} | {largest(['CAR-SAL', 'CAR-BCH'])} | {', '.join(soc)} |")
    w("")

    # Large events with a size, any place in scope
    w("## 4. RQ3, RQ4 Events with a stated size (scope countries)")
    w("")
    w("| Event | Place | Date | Discipline | Size | Evidence | Red Bull |")
    w("|---|---|---|---|---|---|---|")
    sized = [e for e in events.values() if e["scale_value"] and e["scale_type"] != "none"
             and (e["place_id"] in CITIES or e["place_id"] in COUNTRIES or places.get(e["place_id"], {}).get("country_iso2") in COUNTRIES)]
    for e in sorted(sized, key=lambda e: (e["disc_id"], -float(e["scale_value"]))):
        pname = places.get(e["place_id"], {}).get("name", e["place_id"])
        w(f"| {e['name']} | {pname} | {e['date_start']} | {e['disc_id']} | {fmt_num(e['scale_value'])} {e['scale_type']} | "
          f"{e['scale_evidence']} | {e['red_bull_involvement']} |")
    w("")

    # Audience
    w("## 5. RQ4 Audience: video channels")
    w("")
    w("| Channel | Applies to | Subscribers | Source row |")
    w("|---|---|---|---|")
    for f in real:
        if f["signal_id"] == "MED" and f["place_id"] == "GLOBAL" and f["unit"] == "YouTube subscribers (channel page)":
            name = f["notes"].split(" | ")[-1].split(",")[0].split(" read ")[0]
            w(f"| {name} | {DLABEL.get(f['disc_id'], 'all dancesport')} | {fmt_num(val(f))} | {f['fact_id']} |")
    w("")

    # National size figures
    w("## 6. Other national figures on file (breaking-specific or all dance)")
    w("")
    for f in real:
        if f["place_id"] in COUNTRIES and f["signal_id"] in ("ATH", "ORG", "COM", "SCH") and f["disc_id"] in DISCS + ["ALL"] \
                and "Red Bull" not in f["unit"]:
            w(f"- {places[f['place_id']]['name']}, {DLABEL.get(f['disc_id'], 'all dance')}: {fmt_num(val(f))} {f['unit']} ({f['period']}, {f['fact_id']})")
    w("")

    # Social reach and the other round U evidence (hypotheses H1-H3)
    import re
    import statistics
    athletes = {a["athlete_id"]: a for a in load("athletes.csv")}

    def family(d):
        return "Latin" if d.startswith("CAR-") else ("Breaking" if d.startswith("URB-") else "All dance")

    w("## 7. Social reach (round U)")
    w("")
    w("Instagram followers as shown on public profile pages (abbreviated counts such as 340K are rounded by the platform).")
    w("")
    dancers = defaultdict(list)
    for f in real:
        if f["unit"] == "Instagram followers (profile page)" and f["place_id"] == "GLOBAL":
            m = re.search(r"A\d{5}", f["notes"])
            if m and m.group(0) in athletes:
                dancers[family(f["disc_id"])].append((float(val(f)), athletes[m.group(0)]["public_name"]))
    if dancers:
        w("**Professional dancers (top 30 per world found):**")
        w("")
        w("| World | Dancers | Total followers | Median | Largest |")
        w("|---|---|---|---|---|")
        for fam in ("Latin", "Breaking"):
            rows = sorted(dancers.get(fam, []), reverse=True)
            if rows:
                vals = [r[0] for r in rows]
                top = ", ".join(f"{n} {fmt_num(v)}" for v, n in rows[:3])
                w(f"| {fam} | {len(rows)} | {fmt_num(sum(vals))} | {fmt_num(statistics.median(vals))} | {top} |")
        w("")
    accounts = defaultdict(list)
    for f in real:
        if f["unit"] == "Instagram followers (profile page)" and f["task_id"] == "U3.1":
            m = re.search(r"event account: (.*?) \(id", f["notes"])
            accounts[family(f["disc_id"])].append((float(val(f)), m.group(1) if m else f["fact_id"]))
    if accounts:
        w("**Event and competition accounts:**")
        w("")
        w("| World | Accounts | Largest (Instagram followers) |")
        w("|---|---|---|")
        for fam in ("Latin", "Breaking", "All dance"):
            rows = sorted(accounts.get(fam, []), reverse=True)
            if rows:
                w(f"| {fam} | {len(rows)} | " + ", ".join(f"{n} {fmt_num(v)}" for v, n in rows[:6]) + " |")
        w("")
    tags = [f for f in real if f["unit"] == "Instagram hashtag posts"]
    if tags:
        def tag(f):
            m = re.search(r"#\w+", f["notes"])
            return m.group(0) if m else f["disc_id"]
        w("**Hashtags (Instagram reels count shown on the public tag page):** " + "; ".join(
            f"{tag(f)} {fmt_num(val(f))}" for f in tags))
        w("")
    vids = defaultdict(list)
    for f in real:
        if f["unit"] == "YouTube views, top dance video (non-competition)":
            title = f["notes"].split("|")[0].replace("Title:", "").strip()
            vids[family(f["disc_id"])].append((float(val(f)), title))
    if vids:
        w("**Most viewed videos outside Red Bull competitions (top 3 per world):**")
        w("")
        for fam in ("Latin", "Breaking"):
            rows = sorted(vids.get(fam, []), reverse=True)[:3]
            w(f"- {fam}: " + "; ".join(f"{t} ({fmt_num(v)})" for v, t in rows))
        w("")

    w("## 8. Congress market and Red Bull precedents (round U)")
    w("")
    gd = defaultdict(dict)
    for f in real:
        if f["unit"] in ("Latin events listed on goandance.com, next 12 months", "breaking events listed on and8.dance, next 12 months"):
            gd[f["place_id"]][f["disc_id"]] = fmt_num(val(f))
    if gd:
        w("Events listed for the next 12 months (two different platforms: compare countries within a column, not the columns):")
        w("")
        w("| Country | Salsa (goandance) | Bachata (goandance) | Breaking (and8.dance) |")
        w("|---|---|---|---|")
        for c in COUNTRIES:
            if c in gd:
                d = gd[c]
                w(f"| {places[c]['name']} | {d.get('CAR-SAL', 'nf')} | {d.get('CAR-BCH', 'nf')} | {d.get('URB-BRK', 'nf')} |")
        w("")
    prec = [e for e in events.values() if e["task_id"] == "U1"]
    if prec:
        w("Red Bull participation activations found (U1; no precedent at a Latin congress was found in the 9 countries):")
        w("")
        for e in prec:
            w(f"- {e['name']} ({places.get(e['place_id'], {}).get('name', e['place_id'])}, {e['date_start']})")
        w("")

    # What is left outside
    in_scope =[f for f in real if (f["place_id"] in CITIES + COUNTRIES + ["GLOBAL"]) and f["disc_id"] in DISCS + ["ALL"]]
    used_units = {i[4] for i in INDICATORS if i[4]} | {"rungs present", "YouTube subscribers (channel page)"}
    other = [f for f in in_scope if f["unit"] not in used_units and f["signal_id"] not in ("POP",)
             and not f["task_id"].startswith("U")
             and not f["unit"].startswith("events listed on")]
    w("## 9. Rows on file not used above")
    w("")
    w(f"{len(other)} usable rows in scope use other units (mostly older single-site listing counts, prices in mixed units, Wikipedia views, students and tourism). "
      "They stay in data/ but are not comparable across cities and are not part of the research questions.")
    w("")

    with open(OUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(out))
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
